export function getCategoryById(idOrName: string): CategoryInfo | undefined {
  return categoryDefinitions.find(
    (c) =>
      c.id === idOrName ||
      c.name.toLowerCase() === idOrName.toLowerCase() ||
      c.id.toLowerCase() === idOrName.toLowerCase().replace(/\s*&\s*/g, '-')
  );
}

